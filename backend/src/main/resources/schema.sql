-- Neteja per evitar errors (primer les filles)
DROP TABLE IF EXISTS animal_medication;
DROP TABLE IF EXISTS animal_vaccine;
DROP TABLE IF EXISTS medication;
DROP TABLE IF EXISTS vaccine;
DROP TABLE IF EXISTS missingAnimal;
DROP TABLE IF EXISTS adoptAnimal;


-- =============================================================================
--                              CREACIÓ DE TAULES
-- =============================================================================
-- Taula d'animals en adopció
CREATE TABLE IF NOT EXISTS adoptAnimal (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom               VARCHAR(25),
    descripcio       VARCHAR (255),
    dataNaixament     DATE,
    ubicacio          VARCHAR(255),
    especie           VARCHAR (25),
    esterilitzat      BOOLEAN,
    adoptat           BOOLEAN DEFAULT FALSE
);

-- Taula d'animals perduts
CREATE TABLE IF NOT EXISTS missingAnimal (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom               VARCHAR(25),
    descripcio        VARCHAR(255),
    zona              VARCHAR(255),
    especie           VARCHAR(25),
    xip               BOOLEAN,
    telContacte       VARCHAR(25),
    mailContacte      VARCHAR(50),
    trobat            BOOLEAN DEFAULT FALSE
);

-- Catàleg de vacunes
CREATE TABLE IF NOT EXISTS vaccine (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nomVacuna         VARCHAR(255)
);

-- Catàleg de medicaments
CREATE TABLE IF NOT EXISTS medication (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nomMedicament     VARCHAR(255)
);

-- Taula auxiliar: Animals <-> Vacunes
CREATE TABLE IF NOT EXISTS animal_vaccine (
    idAnimal          BIGINT REFERENCES adoptAnimal(id) ON DELETE CASCADE,
    idVaccine         BIGINT REFERENCES vaccine(id) ON DELETE CASCADE,
    PRIMARY KEY (idAnimal, idVaccine)
);

-- Taula auxiliar: Animals <-> Medicaments
CREATE TABLE IF NOT EXISTS animal_medication (
    idAnimal          BIGINT REFERENCES adoptAnimal(id) ON DELETE CASCADE,
    idMedication      BIGINT REFERENCES medication(id) ON DELETE CASCADE,
    cronic            BOOLEAN DEFAULT FALSE,
    PRIMARY KEY (idAnimal, idMedication)
);
